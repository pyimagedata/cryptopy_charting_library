let currentLang: LanguageCode = 'en';

const languageListeners = new Set<(lang: LanguageCode) => void>();

/** Subscribe to language changes (fired only when the language actually changes). Returns an unsubscribe fn. */
export function onLanguageChange(cb: (lang: LanguageCode) => void): () => void {
    languageListeners.add(cb);
    return () => { languageListeners.delete(cb); };
}

export function setLanguage(lang: LanguageCode) {
    const prev = currentLang;
    // Dynamic validation based on available translations
    if (TRANSLATIONS[lang]) {
        currentLang = lang;
    } else {
        console.warn(`Language ${lang} not supported, falling back to English`);
        currentLang = 'en';
    }
    if (currentLang !== prev) {
        for (const cb of Array.from(languageListeners)) {
            try { cb(currentLang); } catch (e) { console.error('language listener failed', e); }
        }
    }
}

export function t(key: string): string {
    if (currentLang === 'en') return key;
    const dict = TRANSLATIONS[currentLang];
    return dict?.[key] || key;
}

export function getCurrentLanguage(): LanguageCode {
    return currentLang;
}
